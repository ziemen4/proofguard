// Evaluate a call against exactly the source snapshot admitted by the supervisor.
// This process never loads project imports or parses argument declarations.
import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { encodePrimitiveIO, runtimeInputTerm, runtimeOwnerTerm, runtimeResponseTerm } from './io.mjs';

const B = await import(pathToFileURL(`${process.argv[2]}/bend.ts`));
const { inputs, call } = JSON.parse(fs.readFileSync(0, 'utf8'));

try {
  const book = B.book_nil();
  for (const source of inputs.contract.sources) {
    B.parse_book(book, '', source.content, '', Object.create(null));
  }
  const ownerFunctions = new Set(Object.entries(book.tlds)
    .filter(([, value]) => value.$ === 'Def' && value.v !== null).map(([name]) => name));
  for (const source of inputs.candidate) {
    B.parse_book(book, '', source.content, '', Object.create(null));
  }
  // Source and mandatory laws were already accepted by admission. Evaluate the
  // original program; verifier modules, facts and managed proof fills stay out
  // of this process. Verification rejects runtime dependencies on those values.
  if (call.schema !== 1 || call.function !== inputs.execution_entrypoint
      || !(inputs.contract.project.implementations.includes(call.function)
        || ownerFunctions.has(call.function))) {
    throw new Error('Execution entrypoint must belong to the frozen owner contract');
  }
  let expression = B.Ref(call.function);
  let closedOwnerCall = false;
  if (Object.hasOwn(call, 'private_inputs') || Object.hasOwn(call, 'owner_context')) {
    // Check the fixed interface with symbolic variables. The argument codec
    // constructs only closed inhabitants of these two owner-defined datatypes;
    // re-inferring millions of generated byte constructors duplicates that work.
    const root = { t: B.Ref('__bendspec_call'), n: 0, def: '__bendspec_call', qs: [] };
    const first = B.term_wnf(book, B.term_infer(book, root, expression, B.Lone(), B.ctx_nil(), 0).ty);
    if (first.$ !== 'All' || !B.term_compare('EQ', book, first.A, B.Ref('PGInputs'))) {
      throw new Error('Owner entrypoint must accept PGInputs');
    }
    const second = B.term_wnf(book, first.B(B.Var('__pg_inputs', 0)));
    const withOwner = Object.hasOwn(call, 'owner_context');
    if (withOwner) {
      if (second.$ !== 'All' || !B.term_compare('EQ', book, second.A, B.Ref('PGOwnerContext'), 1)
          || !B.term_compare('EQ', book, second.B(B.Var('__pg_owner', 1)), B.Ref('PGIO'), 2)) {
        throw new Error('Owner entrypoint must have the fixed private execution signature');
      }
    } else if (!B.term_compare('EQ', book, second, B.Ref('PGIO'), 1)) {
      throw new Error('Application entrypoint must return PGIO');
    }
    expression = B.App(expression, runtimeInputTerm(B, call.private_inputs));
    if (withOwner) expression = B.App(expression, runtimeOwnerTerm(B, call.owner_context));
    closedOwnerCall = true;
  }
  const checked = closedOwnerCall ? { tm: expression, ty: B.Ref('PGIO') } : B.term_infer(book,
    { t: B.Ref('__bendspec_call'), n: 0, def: '__bendspec_call', qs: [] },
    expression, B.Lone(), B.ctx_nil(), 0);
  if (book.hols !== 0) throw new Error('Incomplete application');
  // Reduce only the head of PGIO: a continuation stays closed until the host
  // supplies its response, so a pending call never runs the code after it.
  const reduce = { head: term => B.term_wnf(book, term), full: term => B.term_snf(book, term),
    resume: (next, response) => B.App(next, runtimeResponseTerm(B, response)) };
  const responses = call.responses ?? [];
  if (!Array.isArray(responses) || responses.length > 16) throw new Error('Invalid recorded responses');
  process.stdout.write(JSON.stringify({schema: 1, status: 'evaluated',
    value: encodePrimitiveIO(checked.tm, reduce, responses)}) + '\n');
} catch (error) {
  process.stderr.write(JSON.stringify({schema: 1, status: 'rejected',
    message: String(error).slice(0, 12000)}) + '\n');
  process.exitCode = 1;
}
